#!/usr/bin/env node
// Build-time generator for linktree /gh: lists every GitHub Pages site of the owner.
// Reads the GitHub API (repos with has_pages + the pages endpoint for custom domains)
// and writes src/data/gh-pages.json (+ its PORTAL_DATA wrapper, + dist copy when dist/
// exists). The page itself makes no API calls. Run by .github/workflows/gh-pages-list.yml.
// Usage: GH_TOKEN=... node scripts/gh-pages-gen.mjs [owner]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const owner = process.argv[2] || "diegonmarcos";
const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN || "";
const headers = { Accept: "application/vnd.github+json", "User-Agent": "linktree-gh-pages-gen" };
if (token) headers.Authorization = `Bearer ${token}`;

async function api(url) {
  const r = await fetch(url.startsWith("http") ? url : `https://api.github.com${url}`, { headers });
  if (!r.ok) throw Object.assign(new Error(`${url} -> ${r.status}`), { status: r.status });
  return r.json();
}

async function customDomain(repo) {
  try {
    const p = await api(`/repos/${owner}/${repo.name}/pages`);
    return { cname: p.cname || "", html_url: p.html_url || "" };
  } catch {
    // Pages endpoint needs push access; fall back to the CNAME file on the default branch.
    try {
      const r = await fetch(`https://raw.githubusercontent.com/${owner}/${repo.name}/${repo.default_branch}/CNAME`);
      if (r.ok) return { cname: (await r.text()).trim().split(/\s+/)[0] || "", html_url: "" };
    } catch {}
    return { cname: "", html_url: "" };
  }
}

const repos = [];
for (let page = 1; ; page++) {
  const batch = await api(`/users/${owner}/repos?per_page=100&type=owner&page=${page}`);
  repos.push(...batch);
  if (batch.length < 100) break;
}

const sites = [];
for (const repo of repos.filter((r) => r.has_pages && !r.private)) {
  const { cname, html_url } = await customDomain(repo);
  const fallback = repo.name.toLowerCase() === `${owner}.github.io`.toLowerCase()
    ? `https://${owner}.github.io/` : `https://${owner}.github.io/${repo.name}/`;
  sites.push({
    repo: repo.name,
    url: cname ? `https://${cname}/` : (html_url || fallback),
    custom_domain: cname || null,
    description: repo.description || "",
    updated: (repo.pushed_at || repo.updated_at || "").slice(0, 10),
    repo_url: repo.html_url,
    archived: !!repo.archived,
  });
}
sites.sort((a, b) => b.updated.localeCompare(a.updated) || a.repo.localeCompare(b.repo));

const out = path.join(root, "src/data/gh-pages.json");
let prev = null;
try { prev = JSON.parse(fs.readFileSync(out, "utf8")); } catch {}
if (prev && JSON.stringify(prev.sites) === JSON.stringify(sites)) {
  console.log(`gh-pages: ${sites.length} sites, unchanged`);
  process.exit(0);
}

const data = {
  _description: `GitHub Pages sites of ${owner}. GENERATED by scripts/gh-pages-gen.mjs from the GitHub API at build time; consumed by gh.html with no runtime API calls.`,
  owner,
  generated: new Date().toISOString().slice(0, 10),
  sites,
};
const json = JSON.stringify(data, null, 2);
const wrapper =
  `// GENERATED FROM gh-pages.json by scripts/gh-pages-gen.mjs — DO NOT EDIT BY HAND.\n` +
  `(function () {\n  var g = (typeof globalThis !== "undefined") ? globalThis : (typeof window !== "undefined" ? window : this);\n` +
  `  g.PORTAL_DATA = g.PORTAL_DATA || {};\n  g.PORTAL_DATA["gh-pages"] = ${json}\n;\n})();\n`;
fs.writeFileSync(out, json + "\n");
fs.writeFileSync(path.join(root, "src/data/data-gh-pages.json.js"), wrapper);
if (fs.existsSync(path.join(root, "dist"))) fs.writeFileSync(path.join(root, "dist/data-gh-pages.json.js"), wrapper);
console.log(`gh-pages: ${sites.length} sites written`);
