#!/usr/bin/env node
// Generates the ONE shared top nav of the cloud web apps (_shared/dist/nav.js + nav.css + index.html)
// from the SuperApp app list (a_Portals/cloud-superapp/src/data/cloud-apps.json, itself generated from
// cloud-u-android aa_cloud-superapp/build.json). Every app site includes /cloud-webapps/nav.js + nav.css;
// nothing is copied per site. `--check` fails when the committed output or a site is out of date.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const list = JSON.parse(readFileSync(join(root, '../a_Portals/cloud-superapp/src/data/cloud-apps.json'), 'utf8'));
const ALIAS = { 'cloud-media-center': 'cloud-media', 'cloud-terminal-nix': 'cloud-terminal' }; // extapp id -> APK/site name
const BY_ID = { 'c3-bot': 'c3-bot', 'ai-chat': 'ai-chat', 'cloud-superapp': 'cloud-superapp' };

const apps = [], seen = new Set();
for (const g of list.groups) for (const t of g.tiles) {
  let slug = null;
  const m = /^extapp:([a-z0-9-]+)/.exec(t.target || '');
  if (m) slug = ALIAS[m[1]] ?? m[1]; else if (t.id && BY_ID[t.id]) slug = BY_ID[t.id];
  if (!slug || seen.has(slug)) continue;
  seen.add(slug); apps.push({ slug, label: t.label || slug, group: g.title });
}
const missing = apps.filter(a => !existsSync(join(root, a.slug, 'src/index.html'))).map(a => a.slug);
const extra = readdirSync(root).filter(d => existsSync(join(root, d, 'build.json')) && !seen.has(d));
if (missing.length || extra.length) { console.error('nav/site mismatch', { missing, extra }); process.exit(1); }

const css = `#cwa-nav{position:sticky;top:0;z-index:99;display:flex;gap:4px;overflow-x:auto;padding:6px 10px;background:#0b0f17;border-bottom:1px solid #243049;font:13px system-ui,sans-serif;scrollbar-width:thin}
#cwa-nav a{flex:none;padding:5px 10px;border-radius:8px;color:#9aa4b2;text-decoration:none;white-space:nowrap}
#cwa-nav a:hover{color:#e6e9ef}#cwa-nav a[aria-current]{background:#4cc2ff;color:#04121c;font-weight:600}
#cwa-nav a.home{color:#4cc2ff;font-weight:700}
`;
const js = `/* GENERATED by cloud-webapps/scripts/gen-nav.mjs from the SuperApp app list - DO NOT EDIT. */
(function(){var B='/cloud-webapps/',A=${JSON.stringify(apps.map(a => [a.slug, a.label]))};
var cur=(location.pathname.split(B)[1]||'').split('/')[0];
var n=document.createElement('nav');n.id='cwa-nav';n.setAttribute('aria-label','Cloud apps');
n.innerHTML='<a class="home" href="'+B+'">Cloud</a>'+A.map(function(a){return '<a href="'+B+a[0]+'/"'+(a[0]===cur?' aria-current="page"':'')+'>'+a[1]+'</a>'}).join('');
function put(){document.body.insertBefore(n,document.body.firstChild);var c=n.querySelector('[aria-current]');if(c&&c.scrollIntoView)c.scrollIntoView({inline:'center',block:'nearest'})}
if(document.body)put();else document.addEventListener('DOMContentLoaded',put);})();
`;
const index = `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Cloud web apps</title>
<link rel="stylesheet" href="/cloud-webapps/nav.css"><script src="/cloud-webapps/nav.js" defer></script>
<style>body{margin:0;background:#0b0f17;color:#e6e9ef;font:16px/1.5 system-ui,sans-serif}main{max-width:860px;margin:0 auto;padding:24px 16px}a{color:#4cc2ff}ul{columns:2;padding-left:1.2em}</style></head>
<body><main><h1>Cloud web apps</h1><p>One independent site per Cloud APK.</p><ul>${apps.map(a => `<li><a href="/cloud-webapps/${a.slug}/">${a.slug}</a> <small>${a.label}</small></li>`).join('')}</ul></main></body></html>
`;
const inc = '<link rel="stylesheet" href="/cloud-webapps/nav.css"><script src="/cloud-webapps/nav.js" defer></script>';
const out = { '_shared/dist/nav.js': js, '_shared/dist/nav.css': css, '_shared/dist/index.html': index };
for (const a of apps) for (const sub of ['src', 'dist']) {
  const f = `${a.slug}/${sub}/index.html`;
  if (!existsSync(join(root, f))) continue;
  let h = readFileSync(join(root, f), 'utf8');
  h = h.replace(/<link rel="stylesheet" href="\/cloud-webapps\/nav\.css"><script src="\/cloud-webapps\/nav\.js" defer><\/script>\n?/, '');
  h = h.replace(/<nav class="crumbs">.*?<\/nav>/s, '<nav class="crumbs"><a href="/cloud-webapps/">Cloud apps</a> / ' + a.label + '</nav>');
  out[f] = h.replace('</head>', inc + '\n</head>');
}
let bad = 0;
for (const [f, c] of Object.entries(out)) {
  const p = join(root, f);
  if (process.argv.includes('--check')) { if (!existsSync(p) || readFileSync(p, 'utf8') !== c) { console.error('stale', f); bad++; } }
  else writeFileSync(p, c);
}
if (bad) process.exit(1);
console.log(`${apps.length} apps, one shared nav`);
